func writeInventory(path string, tests []string, sha string) error {
	var b strings.Builder
	b.WriteString("# Generated by tools/syncpint. Do not hand-edit test ids;\n")
	b.WriteString("# re-run syncpint after upgrading Pint.\n")
	fmt.Fprintf(&b, "pint_sha: %s\n", sha)
	b.WriteString("tests:\n")
	for _, id := range tests {
		st, reason, goFile := classify(id)
		fmt.Fprintf(&b, "  - id: %q\n", id)
		fmt.Fprintf(&b, "    status: %s\n", st)
		if reason != "" {
			fmt.Fprintf(&b, "    reason: %q\n", reason)
		}
		if goFile != "" {
			fmt.Fprintf(&b, "    go: %s\n", goFile)
		}
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, []byte(b.String()), 0o644)
}

func parseInventoryIDs(path string) (map[string]struct{}, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	ids := map[string]struct{}{}
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if strings.HasPrefix(line, "- id:") {
			v := strings.TrimSpace(strings.TrimPrefix(line, "- id:"))
			v = strings.Trim(v, `"'`)
			ids[v] = struct{}{}
		}
	}
	return ids, sc.Err()
}

func main() {
	pint := flag.String("pint", "", "path to a Pint checkout")
	flag.Parse()
	root, _ := os.Getwd()
	for {
		if _, err := os.Stat(filepath.Join(root, "go.mod")); err == nil {
			break
		}
		parent := filepath.Dir(root)
		if parent == root {
			fmt.Fprintln(os.Stderr, "go.mod not found")
			os.Exit(1)
		}
		root = parent
	}

	pintRoot := *pint
	if pintRoot == "" {
		pintRoot = filepath.Join(filepath.Dir(root), "pint")
	}
	suite := filepath.Join(pintRoot, "pint", "testsuite")
	if _, err := os.Stat(suite); err != nil {
		fmt.Fprintf(os.Stderr, "Pint testsuite not found at %s (pass --pint)\n", suite)
		os.Exit(1)
	}

	shaB, _ := os.ReadFile(filepath.Join(pintRoot, ".git", "HEAD"))
	sha := strings.TrimSpace(string(shaB))
	if strings.HasPrefix(sha, "ref:") {
		ref := strings.TrimSpace(strings.TrimPrefix(sha, "ref:"))
		if b, err := os.ReadFile(filepath.Join(pintRoot, ".git", ref)); err == nil {
			sha = strings.TrimSpace(string(b))
		}
	}
	if len(sha) > 7 {
		sha = sha[:7]
	}

	if err := copyFile(filepath.Join(pintRoot, "pint", "default_en.txt"), filepath.Join(root, "defs", "default_en.txt")); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if err := copyFile(filepath.Join(pintRoot, "pint", "constants_en.txt"), filepath.Join(root, "defs", "constants_en.txt")); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	_ = os.WriteFile(filepath.Join(root, "PINT_SHA"), []byte(sha+"\n"), 0o644)

	tests, err := extractTests(suite)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	inv := filepath.Join(root, "testdata", "inventory.yml")
	old, _ := parseInventoryIDs(inv)
	if err := writeInventory(inv, tests, sha); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	var added, removed []string
	now := map[string]struct{}{}
	for _, id := range tests {
		now[id] = struct{}{}
		if _, ok := old[id]; !ok && len(old) > 0 {
			added = append(added, id)
		}
	}
	for id := range old {
		if _, ok := now[id]; !ok {
			removed = append(removed, id)
		}
	}
	fmt.Printf("Pint SHA %s: %d tests in inventory\n", sha, len(tests))
	if len(added) > 0 {
		fmt.Printf("new tests (%d):\n", len(added))
		for _, id := range added {
			fmt.Println(" +", id)
		}
	}
	if len(removed) > 0 {
		fmt.Printf("removed tests (%d):\n", len(removed))
		for _, id := range removed {
			fmt.Println(" -", id)
		}
	}
}
