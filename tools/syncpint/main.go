var (
	reClass    = regexp.MustCompile(`^class\s+(\w+)`)
	reFunc     = regexp.MustCompile(`^def\s+(test_\w+)`)
	reMethod   = regexp.MustCompile(`^\s{4}def\s+(test_\w+)`)
	reIndentFn = regexp.MustCompile(`^(\s*)def\s+(test_\w+)`)
)

func extractTests(root string) ([]string, error) {
	var out []string
	err := filepath.Walk(root, func(path string, info os.FileInfo, err error) error {
		if err != nil {
			return err
		}
		if info.IsDir() || !strings.HasPrefix(info.Name(), "test_") || !strings.HasSuffix(path, ".py") {
			return nil
		}
		rel, _ := filepath.Rel(root, path)
		rel = filepath.ToSlash(rel)
		f, err := os.Open(path)
		if err != nil {
			return err
		}
		defer f.Close()
		class := ""
		sc := bufio.NewScanner(f)
		for sc.Scan() {
			line := sc.Text()
			if m := reClass.FindStringSubmatch(line); m != nil {
				class = m[1]
				continue
			}
			if strings.HasPrefix(line, "def ") {
				class = ""
			}
			if m := reFunc.FindStringSubmatch(line); m != nil && strings.HasPrefix(line, "def ") {
				out = append(out, rel+"::"+m[1])
				continue
			}
			if class != "" {
				if m := reMethod.FindStringSubmatch(line); m != nil {
					out = append(out, rel+"::"+class+"."+m[1])
				}
			}
		}
		return sc.Err()
	})
	sort.Strings(out)
	return out, err
}

func copyFile(src, dst string) error {
	b, err := os.ReadFile(src)
	if err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(dst), 0o755); err != nil {
		return err
	}
	return os.WriteFile(dst, b, 0o644)
}

